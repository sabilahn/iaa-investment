    public function __construct()
    {
        parent::__construct();

        $project_key = 'iaa-investment';

        $possible_env_paths = [
            dirname(FCPATH, 2) . DIRECTORY_SEPARATOR . '.env_config' . DIRECTORY_SEPARATOR . $project_key . '.php',
            dirname(FCPATH, 2) . DIRECTORY_SEPARATOR . '.env_config' . DIRECTORY_SEPARATOR . $project_key . '.env.php',
            dirname(FCPATH, 2) . DIRECTORY_SEPARATOR . '.env_config' . DIRECTORY_SEPARATOR . '.env.php',
            dirname(FCPATH, 2) . DIRECTORY_SEPARATOR . '.env_config' . DIRECTORY_SEPARATOR . '.env',

            dirname(FCPATH, 1) . DIRECTORY_SEPARATOR . '.env_config' . DIRECTORY_SEPARATOR . $project_key . '.php',
            dirname(FCPATH, 1) . DIRECTORY_SEPARATOR . '.env_config' . DIRECTORY_SEPARATOR . $project_key . '.env.php',
            dirname(FCPATH, 1) . DIRECTORY_SEPARATOR . '.env_config' . DIRECTORY_SEPARATOR . '.env.php',
            dirname(FCPATH, 1) . DIRECTORY_SEPARATOR . '.env_config' . DIRECTORY_SEPARATOR . '.env',

            (! empty($_SERVER['HOME']) ? rtrim($_SERVER['HOME'], '/\\') . DIRECTORY_SEPARATOR . '.env_config' . DIRECTORY_SEPARATOR . $project_key . '.php' : ''),

            FCPATH . '.env.php',
            FCPATH . '.env',
        ];

        defined('BASEPATH') || define('BASEPATH', SYSTEMPATH);

        $env_db = [];
        foreach ($possible_env_paths as $env_path) {
            if ($env_path !== '' && is_file($env_path)) {
                $loaded_env = @include $env_path;
                if (is_array($loaded_env) && ! empty($loaded_env['DB_USER'])) {
                    $env_db = $loaded_env;
                    break;
                }
                if (is_array($loaded_env) && empty($env_db)) {
                    $env_db = $loaded_env;
                }
            }
        }

        $this->default['DSN']      = $env_db['DB_DSN'] ?? '';
        $this->default['hostname'] = ! empty($env_db['DB_HOST']) ? $env_db['DB_HOST'] : 'localhost';
        $this->default['username'] = ! empty($env_db['DB_USER']) ? $env_db['DB_USER'] : 'root';
        $this->default['password'] = $env_db['DB_PASS'] ?? '';
        $this->default['database'] = ! empty($env_db['DB_NAME']) ? $env_db['DB_NAME'] : 'dharmaia_investment';
        $driver                    = strtolower($env_db['DB_DRIVER'] ?? 'mysqli');
        $this->default['DBDriver'] = ($driver === 'mysqli') ? 'MySQLi' : ($env_db['DB_DRIVER'] ?? 'MySQLi');

        // Ensure that we always set the database group to 'tests' if
        // we are currently running an automated test suite, so that
        // we don't overwrite live data on accident.
        if (ENVIRONMENT === 'testing') {
            $this->defaultGroup = 'tests';
        }
    }
